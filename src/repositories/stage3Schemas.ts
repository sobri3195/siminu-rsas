import { z } from "zod";
import { contentSchema } from "./drafts";
const base = z.object({ id: z.string().min(1) }).passthrough();
const kind = z.enum([
  "Nota dinas",
  "Surat undangan",
  "Surat pengantar",
  "Surat tugas",
  "Laporan kegiatan",
]);
export const stage3Schemas = {
  templates: base.extend({
    name: z.string(),
    kind,
    official: z.boolean(),
    content: contentSchema,
    updatedAt: z.iso.datetime(),
  }),
  drafts: base.extend({
    templateId: z.string(),
    kind,
    content: contentSchema,
    unitId: z.string(),
    authorId: z.string(),
    reviewerIds: z.array(z.string()),
    reviewIndex: z.number().int().nonnegative(),
    version: z.number().int().positive(),
    revision: z.number().int().positive(),
    stage: z.enum([
      "Draf",
      "Pemeriksaan",
      "Perbaikan",
      "Persetujuan",
      "Penomoran",
      "Pengiriman",
    ]),
    attachmentIds: z.array(z.string()),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
  }),
  draftVersions: base.extend({
    draftId: z.string(),
    version: z.number().int().positive(),
    content: contentSchema,
    authorId: z.string(),
    reason: z.string(),
    createdAt: z.iso.datetime(),
  }),
  draftDecisions: base.extend({
    draftId: z.string(),
    version: z.number().int().positive(),
    action: z.enum([
      "Diajukan",
      "Dikembalikan",
      "Paraf simulasi",
      "Disetujui simulasi",
      "Diberi nomor",
      "Persetujuan tidak berlaku",
      "Dipulihkan",
    ]),
    userId: z.string(),
    note: z.string(),
    createdAt: z.iso.datetime(),
  }),
  minutes: base.extend({
    title: z.string(),
    date: z.iso.date(),
    chair: z.string(),
    participants: z.string(),
    discussion: z.string(),
    decisions: z.array(
      z.object({
        id: z.string(),
        text: z.string(),
        userId: z.string(),
        unitId: z.string(),
        deadline: z.iso.date(),
        taskId: z.string().optional(),
      }),
    ),
    attachmentIds: z.array(z.string()),
    revision: z.number().int().positive(),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
  }),
  caseFiles: base.extend({
    title: z.string(),
    description: z.string(),
    links: z.array(
      z.object({
        kind: z.enum([
          "letters",
          "dispositions",
          "tasks",
          "outgoing",
          "events",
          "minutes",
          "reports",
          "drafts",
        ]),
        id: z.string(),
      }),
    ),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
  }),
  searchPages: base.extend({
    attachmentId: z.string(),
    page: z.number().int().nonnegative(),
    text: z.string(),
    status: z.enum(["text", "scan", "error"]),
    indexedAt: z.iso.datetime(),
  }),
};
