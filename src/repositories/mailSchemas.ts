import { z } from "zod";
const key = z.string().min(1),
  base = z.object({ id: key }),
  time = z.iso.datetime(),
  date = z.union([z.iso.date(), z.literal("")]);
export const mailSchemas = {
  replyAssignments: base.extend({
    decision: z.enum([
      "Perlu penilaian",
      "Perlu balasan",
      "Tidak perlu balasan",
    ]),
    picId: z.string(),
    picName: z.string(),
    unitId: z.string(),
    unitName: z.string(),
    deadline: date,
    instructions: z.string(),
    reviewerId: z.string(),
    reason: key,
    revision: z.number().int().positive(),
    updatedAt: time,
    userId: key,
  }),
  mailNumbers: base.extend({
    draftId: key,
    version: z.number().int().positive(),
    outgoingId: key,
    createdAt: time,
    userId: key,
    state: z.enum(["Digunakan", "Dibatalkan"]),
    reason: z.string(),
  }),
  dispatchTargets: base.extend({
    outgoingId: key,
    name: key,
    address: z.string(),
    createdAt: time,
  }),
  dispatches: base.extend({
    attempt: z.number().int().positive().optional(),
    targetId: key,
    outgoingId: key,
    recipient: key,
    sentAt: time,
    medium: z.enum([
      "Diserahkan langsung",
      "Kurir",
      "Pos",
      "Email manual",
      "Lainnya",
    ]),
    userId: key,
    userName: key,
    tracking: z.string(),
    proofIds: z.array(key),
    receivedAt: z.union([time, z.literal("")]),
    receiptIds: z.array(key),
    note: z.string(),
    status: z.enum([
      "Tercatat dikirim",
      "Diterima",
      "Gagal dikirim",
      "Dikirim ulang",
    ]),
    revision: z.number().int().positive(),
    createdAt: time,
  }),
  mailLinks: base.extend({
    fromId: key,
    toId: key,
    reason: key,
    userId: key,
    createdAt: time,
  }),
};
