import { z } from "zod";
const date = z.union([z.iso.date(), z.literal("")]),
  text = z.string().max(100000);
export const digitalRecipientSchema = z.object({
  id: z.string().min(1),
  unitId: z.string().min(1),
  unitName: z.string(),
  userId: z.string().min(1),
  userName: z.string(),
  positionId: z.string(),
  positionName: z.string(),
  assignmentStart: date,
  assignmentEnd: date,
  kind: z.enum(["Utama", "Pendukung", "Tembusan"]),
  instruction: text,
  deadline: date,
});
export const dispositionContentSchema = z.object({
  letterId: z.string().min(1),
  giverId: z.string().min(1),
  giver: z.string(),
  giverPosition: z.string(),
  mode: z.enum(["Penugasan", "Untuk diketahui"]),
  recipients: z.array(digitalRecipientSchema).max(100),
  instructions: z.array(z.string()).max(50),
  notes: text,
  deadline: date,
  reportRequired: z.boolean(),
  review: z.boolean(),
  reviewerId: z.string(),
});
const base = z.object({ id: z.string().min(1) });
export const dispositionSchemas = {
  dispositionDrafts: base.extend({
    authorId: z.string(),
    content: dispositionContentSchema,
    revision: z.number().int().positive(),
    createdAt: z.iso.datetime(),
    updatedAt: z.iso.datetime(),
    sourceId: z.string().optional(),
    sourceRevision: z.number().int().positive().optional(),
    reason: z.string(),
    publishedId: z.string().optional(),
  }),
  dispositionVersions: base.extend({
    dispositionId: z.string(),
    version: z.number().int().positive(),
    snapshot: z
      .object({
        digital: z.literal(true),
        issuerId: z.string(),
        issuerPosition: z.string(),
        issuedAt: z.iso.datetime(),
        updatedAt: z.iso.datetime(),
        mode: z.enum(["Penugasan", "Untuk diketahui"]),
        version: z.number().int().positive(),
        revision: z.number().int().positive(),
        reportRequired: z.boolean(),
        reviewerId: z.string(),
        id: z.string(),
        letterId: z.string(),
        giver: z.string(),
        recipients: z.array(digitalRecipientSchema),
        instructions: z.array(z.string()),
        notes: z.string(),
        deadline: date,
        review: z.boolean(),
        createdAt: z.iso.datetime(),
      })
      .passthrough(),
    userId: z.string(),
    reason: z.string(),
    createdAt: z.iso.datetime(),
  }),
  recipientReceipts: base.extend({
    dispositionId: z.string(),
    recipientId: z.string(),
    userId: z.string(),
    unitId: z.string(),
    userName: z.string(),
    positionName: z.string(),
    readAt: z.iso.datetime().optional(),
    retired: z.boolean().optional(),
  }),
  dispositionOutputs: base.extend({
    dispositionId: z.string(),
    taskId: z.string().optional(),
    kind: z.enum(["notes", "events"]),
    targetId: z.string(),
    userId: z.string(),
    createdAt: z.iso.datetime(),
  }),
};
